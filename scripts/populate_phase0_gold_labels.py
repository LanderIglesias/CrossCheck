LABELED_BY = "claude-assisted (read all 4 source documents directly)"


def main() -> None:
    with get_connection() as conn, conn.cursor() as cur:
        claim_ids: dict[str, int] = {}
        for c in CLAIMS:
            cur.execute(
                "SELECT d.id FROM documents d "
                "JOIN quarters q ON q.id = d.quarter_id "
                "JOIN companies co ON co.id = q.company_id "
                "WHERE co.ticker = %s AND d.modality = %s",
                (c.ticker, c.modality),
            )
            row = cur.fetchone()
            if row is None:
                raise RuntimeError(f"No {c.modality} document for {c.ticker} — run make seed first")
            document_id = row[0]
            cur.execute(
                """INSERT INTO claims
                   (document_id, subject, metric, canonical_metric_key, period, value, unit,
                    qualifier, speaker, extraction_method)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,'manual') RETURNING id""",
                (
                    document_id,
                    c.subject,
                    c.metric,
                    c.canonical_metric_key,
                    c.period,
                    c.value,
                    c.unit,
                    c.qualifier,
                    c.speaker,
                ),
            )
            inserted_row = cur.fetchone()
            # Type-narrowing, not a security control: INSERT ... RETURNING id always returns
            # exactly one row.
            assert inserted_row is not None  # nosec B101
            claim_ids[c.key] = inserted_row[0]

        for claim_a_key, claim_b_key, verdict, rationale in LABELS:
            claim_a_id = claim_ids[claim_a_key]
            claim_b_id = claim_ids[claim_b_key] if claim_b_key else None
            cur.execute(
                """INSERT INTO gold_labels (claim_a_id, claim_b_id, verdict, rationale, labeled_by)
                   VALUES (%s,%s,%s,%s,%s)""",
                (claim_a_id, claim_b_id, verdict, rationale, LABELED_BY),
            )

        print(f"Inserted {len(CLAIMS)} claims and {len(LABELS)} gold labels across 5 companies.")


if __name__ == "__main__":
    main()
